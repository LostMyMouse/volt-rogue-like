// Writes docs/override-map.md: every global function that a later script replaces, in index.html load order.
// Volt has no modules, so files extend each other by reassigning globals (`startWave=function(){...}`).
// Usage: node tools/override-map.cjs [--check]   (--check exits 1 if the committed map is out of date)
const fs=require('fs'),path=require('path');
const root=path.join(__dirname,'..'),out=path.join(root,'docs','override-map.md');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const scripts=[...html.matchAll(/<script[^>]+src="([^"?]+\.js)/g)].map(m=>m[1]).filter(s=>s.startsWith('js/'));
const defined=new Map(),chains=new Map();
const declare=/(?:^|[\s;}])function\s+([A-Za-z_$][\w$]*)\s*\(|(?:^|[\s;])(?:const|let|var)\s+([A-Za-z_$][\w$]*)\s*=\s*(?:function\b|\([^)]*\)\s*=>|[A-Za-z_$][\w$]*\s*=>)/gm;
const replace=/(?:^|[\s;{}(])([A-Za-z_$][\w$]*)\s*=\s*(?:async\s+)?function\b/gm;
for(const file of scripts){
 const src=fs.readFileSync(path.join(root,file),'utf8').replace(/\/\/[^\n]*|\/\*[\s\S]*?\*\//g,'');
 for(const m of src.matchAll(declare)){const name=m[1]||m[2];if(!defined.has(name))defined.set(name,file);}
 for(const m of src.matchAll(replace)){const name=m[1],home=defined.get(name);if(!home||home===file&&!chains.has(name))continue;
  const list=chains.get(name)||[];if(!list.includes(file))list.push(file);chains.set(name,list);}
}
const rows=[...chains].filter(([n,l])=>l.some(f=>f!==defined.get(n))).sort((a,b)=>scripts.indexOf(defined.get(a[0]))-scripts.indexOf(defined.get(b[0]))||a[0].localeCompare(b[0]));
const byFile=new Map();for(const [,l] of rows)for(const f of l)byFile.set(f,(byFile.get(f)||0)+1);
const md=['# Function override map','','Generated by `node tools/override-map.cjs`; do not edit by hand.','',
 'Scripts load in `index.html` order and later files extend earlier ones by reassigning global functions,',
 'usually keeping the old one (`const oldX=x; x=function(...a){oldX(...a); ...}`). To know what a function',
 'really does, read its definition and then every file listed after it, in order: the last one runs first.','',
 '| Function | Defined in | Replaced by (in load order) |','|---|---|---|',
 ...rows.map(([n,l])=>`| \`${n}\` | ${defined.get(n)} | ${l.filter(f=>f!==defined.get(n)).join(' → ')} |`),'',
 '## Files that replace the most functions','',
 ...[...byFile].sort((a,b)=>b[1]-a[1]).slice(0,12).map(([f,n])=>`- ${f}: ${n}`),''].join('\n');
if(process.argv.includes('--check')){const now=fs.existsSync(out)?fs.readFileSync(out,'utf8').replace(/\r\n/g,'\n'):'';
 if(now!==md){console.error('docs/override-map.md is out of date. Run node tools/override-map.cjs');process.exit(1);}
 console.log('Override map is current ('+rows.length+' replaced functions).');process.exit(0);}
fs.writeFileSync(out,md);console.log('Wrote docs/override-map.md: '+rows.length+' replaced functions across '+scripts.length+' scripts.');
